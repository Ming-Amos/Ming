import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const require = createRequire(new URL('../packages/runner/package.json',import.meta.url));
const {chromium}=require('playwright');
const root=fileURLToPath(new URL('..',import.meta.url));
const out=path.join(root,'runtime/public-ui-qa');fs.mkdirSync(out,{recursive:true});
const manifest=JSON.parse(fs.readFileSync(path.join(root,'docs/demo-evidence/manifest.json'),'utf8'));
const browser=await chromium.launch();const page=await browser.newPage({viewport:{width:1484,height:1060}});
const errors=[];page.on('pageerror',error=>errors.push(error.message));
const results=[];function check(name,result){results.push({name,passed:!!result});if(!result)throw Error(name);}
try{
  await page.goto(process.env.MING_PUBLIC_URL||'http://127.0.0.1:4182');
  await page.getByText(/公开演示.*真实历史运行/).waitFor();
  check('Public mode is visibly labelled read-only',await page.getByText(/公开演示.*真实历史运行/).isVisible());
  check('Live execution button disabled',await page.getByRole('button',{name:'历史运行回放',exact:true}).isDisabled());
  await page.getByRole('button',{name:'验收记录',exact:true}).click();
  await page.getByRole('button').filter({hasText:manifest.featuredBaselineRunId.slice(0,10)}).click();
  await page.getByRole('button').filter({hasText:'AC-02'}).click();
  await page.locator('.evidence-link img').first().waitFor();
  await page.waitForFunction(()=>[...document.querySelectorAll('.evidence-link img')].every(i=>i.complete&&i.naturalWidth>0));
  check('Evidence images belong to selected real baseline',await page.locator('.evidence-link img').evaluateAll((images,id)=>images.length>=2&&images.every(i=>i.src.includes(id)),manifest.featuredBaselineRunId));
  await page.screenshot({path:path.join(out,'xray-baseline-desktop.png')});
  await page.screenshot({path:path.join(out,'xray-baseline-full.png'),fullPage:true});
  await page.getByRole('button',{name:'查看修复前后对照'}).click();
  await page.getByRole('heading',{name:'已验证修复',exact:true}).waitFor();
  await page.waitForFunction(()=>[...document.querySelectorAll('dialog img')].every(i=>i.complete&&i.naturalWidth>0));
  check('Comparison contains actual before and after images',await page.locator('dialog img').evaluateAll((images,ids)=>ids.every(id=>images.some(i=>i.src.includes(id))),[manifest.featuredBaselineRunId,manifest.featuredRerunId]));
  await page.screenshot({path:path.join(out,'xray-comparison-desktop.png')});
  await page.getByRole('button',{name:'查看修改后的完整运行与截图'}).click();
  await page.getByRole('button',{name:'查看修复前后对照'}).waitFor();
  check('Switching to rerun preserves comparison access',await page.getByRole('button',{name:'查看修复前后对照'}).isVisible());
  await page.reload();
  await page.getByRole('button',{name:'查看修复前后对照'}).waitFor();
  check('Reload restores selected rerun',await page.locator('.evidence-link img').first().getAttribute('src').then(s=>s.includes(manifest.featuredRerunId)));
  await page.getByLabel('验收项目',{exact:true}).selectOption('todo-buggy');
  await page.getByRole('button').filter({hasText:'TODO-03'}).click();
  await page.waitForFunction(()=>[...document.querySelectorAll('.evidence-link img')].every(i=>i.complete&&i.naturalWidth>0));
  check('Second project renders its own criteria',await page.getByRole('button').filter({hasText:'TODO-03'}).isVisible());
  await page.screenshot({path:path.join(out,'xray-todo-desktop.png')});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(out,'xray-mobile.png'),fullPage:true});
  check('Mobile has no horizontal overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  const r=await fetch((process.env.MING_PUBLIC_URL||'http://127.0.0.1:4182')+'/api/run',{method:'POST',headers:{'Content-Type':'application/json'},body:'{}'});
  check('Public server rejects execution',r.status===403);
  check('No frontend JavaScript errors',errors.length===0);
  console.log(JSON.stringify(results));
} finally {fs.writeFileSync(path.join(out,'report.json'),JSON.stringify({results,errors},null,2));await browser.close();}
